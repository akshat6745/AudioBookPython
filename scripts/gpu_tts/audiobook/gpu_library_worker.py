TARGET_LUFS = -18.0
LIMIT = 0.84


def log(msg: str) -> None:
    print(f"[worker {time.strftime('%H:%M:%S')}] {msg}", flush=True)


def http_get(url: str, timeout: int = 120, retries: int = 5) -> bytes:
    if url.startswith("file://"):
        return Path(url[7:]).read_bytes()
    if not (url.startswith("https://") or url.startswith("http://127.0.0.1:")):
        raise ValueError("presigned URL must use https:// (or loopback in local container test)")
    for attempt in range(retries):
        try:
            with urllib.request.urlopen(url, timeout=timeout) as r:
                return r.read()
        except (urllib.error.URLError, OSError) as e:
            if attempt == retries - 1:
                raise RuntimeError(f"GET failed after {retries} attempts ({type(e).__name__})") from None
            time.sleep(2 ** attempt)
    return b""


def http_put(url: str, data: bytes, content_type: str, timeout: int = 180, retries: int = 5) -> None:
    if url.startswith("file://"):
        dest = Path(url[7:])
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(data)
        return
    if not (url.startswith("https://") or url.startswith("http://127.0.0.1:")):
        raise ValueError("presigned URL must use https:// (or loopback in local container test)")
    for attempt in range(retries):
        req = urllib.request.Request(
            url, data=data, method="PUT",
            headers={"Content-Type": content_type, "Content-Length": str(len(data))},
        )
        try:
            with urllib.request.urlopen(req, timeout=timeout) as r:
                if r.status not in (200, 201, 204):
                    raise RuntimeError(f"unexpected HTTP {r.status}")
                return
        except (urllib.error.URLError, OSError, RuntimeError) as e:
            if attempt == retries - 1:
                raise RuntimeError(f"PUT failed after {retries} attempts ({type(e).__name__})") from None
            time.sleep(2 ** attempt)


def decode_chapter_bytes(raw: bytes) -> str:
    try:
        return gzip.decompress(raw).decode("utf-8")
    except (gzip.BadGzipFile, OSError):
        return raw.decode("utf-8")


def _file_sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        while chunk := f.read(8 * 1024 * 1024):
            h.update(chunk)
    return h.hexdigest()


def ensure_tagger_model(bundle: dict, work: Path) -> Path:
    """Download deberta3large_teacher2 checkpoint from presigned GETs and verify SHA256SUMS."""
    model_name = bundle["settings"]["model"]
    dest = work / "models" / model_name
    done_flag = dest / ".verified"
    if done_flag.exists():
        return dest
    dest.mkdir(parents=True, exist_ok=True)
    log(f"downloading emotion tagger {model_name} ...")
    for fname, url in bundle["model_files"].items():
        target = dest / fname
        if url.startswith("file://"):
            src = Path(url[len("file://"):])
            if target.exists():
                target.unlink()
            try:
                os.link(src, target)
            except OSError:
                target.write_bytes(src.read_bytes())
        else:
            target.write_bytes(http_get(url, timeout=300))
    sums = dict(reversed(ln.split()) for ln in (dest / "SHA256SUMS").read_text().splitlines() if ln.strip())
    for fname in ("model.safetensors", "config.json"):
        actual = _file_sha256(dest / fname)
        if sums.get(fname) != actual:
            sys.exit(f"checksum mismatch for {model_name}/{fname}")
    done_flag.touch()
    log(f"tagger {model_name} verified (sha256 ok)")
    return dest


def ensure_voices(bundle: dict, work: Path) -> tuple[Path, Path, Path]:
    """Write embedded reference WAVs + ref_text to disk and verify sha256."""
    vdir = work / "voices"
    vdir.mkdir(parents=True, exist_ok=True)
    vspec = bundle["voices"]
    for role in ("narrator", "dialogue"):
        raw = base64.b64decode(vspec["wav_b64"][role])
        if hashlib.sha256(raw).hexdigest() != vspec["sha256"][role]:
            sys.exit(f"voice {role} sha256 mismatch")
        (vdir / f"{role}.wav").write_bytes(raw)
    ref_path = vdir / "ref_text.txt"
    ref_path.write_text(vspec["ref_text"])
    (vdir / "voices.json").write_text(json.dumps({
        "narrator": vspec["narrator_name"],
        "dialogue": vspec["dialogue_name"],
    }))
    return vdir / "narrator.wav", vdir / "dialogue.wav", ref_path


def download_novel_chapters(novel_job: dict, ch_dir: Path) -> tuple[dict[int, list[str]], Path]:
    """Download all chapters in parallel via presigned GETs and write titles.json."""
    ch_dir.mkdir(parents=True, exist_ok=True)
    titles: dict[str, str] = {}

    def fetch_one(c: dict) -> tuple[int, list[str]]:
        ch = int(c["chapter"])
        txt_path = ch_dir / f"{ch:05d}.txt"
        if not txt_path.exists():
            text = decode_chapter_bytes(http_get(c["get_text_url"]))
            txt_path.write_text(text, encoding="utf-8")
        return ch, render_mod.paragraphs(txt_path)

    with ThreadPoolExecutor(8) as pool:
        results = dict(pool.map(fetch_one, novel_job["chapters"]))

    for c in novel_job["chapters"]:
        ch = int(c["chapter"])
        titles[str(ch)] = c.get("title") or f"Chapter {ch}"
    titles_path = ch_dir / "titles.json"
    titles_path.write_text(json.dumps(titles, indent=1, ensure_ascii=False))
    return results, titles_path


def run_phase1_archive(bundle: dict, work: Path, novels_filter: set[str] | None) -> None:
    """Single-archive Phase 1: 1 GET for all untagged paragraphs -> GPU span-level tag -> 1 PUT for tags_output.tar.gz (+ tagged chapters)."""
    import io
    import tarfile
    import torch
    import higgs_format as hf
    import tag_novel

    ckpt = ensure_tagger_model(bundle, work)
    arch = bundle["archive"]
    log("downloading single compressed paragraphs archive ...")
    raw_gz = http_get(arch["get_paragraphs_url"], timeout=600)
    actual_sha = hashlib.sha256(raw_gz).hexdigest()
    if arch.get("input_sha256") and actual_sha != arch["input_sha256"]:
        sys.exit(f"archive input sha256 mismatch: expected {arch['input_sha256']}, got {actual_sha}")

    lines = gzip.decompress(raw_gz).decode("utf-8").splitlines()
    by_novel: dict[str, list[dict]] = {}
    for ln in lines:
        if not ln.strip():
            continue
        r = json.loads(ln)
        if novels_filter and r["novel"] not in novels_filter:
            continue
        by_novel.setdefault(r["novel"], []).append(r)

    device = torch.device("cuda" if torch.cuda.is_available() else ("mps" if torch.backends.mps.is_available() else "cpu"))
    bs = 256 if device.type == "cuda" else 32
    model_name = bundle["settings"]["model"]
    out_tags_dir = work / "archive_tags"
    out_ch_dir = out_tags_dir / "chapters"
    out_tags_dir.mkdir(parents=True, exist_ok=True)
    out_ch_dir.mkdir(parents=True, exist_ok=True)
    put_novel_urls = arch.get("put_novel_tag_urls") or {}
    put_ch_urls = arch.get("put_chapter_text_urls") or {}

    total_paras = sum(len(v) for v in by_novel.values())
    log(f"[phase 1 archive] tagging {total_paras:,} paragraphs (narrator + dialogue spans) across {len(by_novel)} novels on {device.type} (bs={bs})")

    # Load model once across all novels so weights aren't reloaded 60 times
    model, tok, max_len = tag_novel.load(Path(ckpt), device)
    t_start = time.perf_counter()
    done_paras = 0
    sums_lines = []

    for novel, rows in by_novel.items():
        if not re.fullmatch(r"[a-z0-9-]+", novel):
            sys.exit(f"invalid novel id: {novel!r}")
        t0 = time.perf_counter()

        # Split every paragraph into narrator and dialogue spans so each gets its own emotion/style/sfx
        span_inputs: list[dict] = []
        para_span_ranges: list[tuple[int, int, list[tuple[str, str]]]] = []
        for r in rows:
            spans = hf.paragraph_spans_for_tagging(r["text"])
            start_idx = len(span_inputs)
            prev_text = r.get("prev", "")
            for s_idx, (voice, s_text) in enumerate(spans):
                span_inputs.append({
                    "text": s_text.strip(),
                    "prev": spans[s_idx - 1][1].strip() if s_idx > 0 else prev_text,
                    "voice": voice,
                })
            para_span_ranges.append((start_idx, len(span_inputs), spans))

        pr = tag_novel.probs(model, tok, max_len, span_inputs, device, bs)
        dt = time.perf_counter() - t0
        heads = tag_novel.HEADS

        # Decode span predictions
        span_preds: list[dict] = []
        for i, sp in enumerate(span_inputs):
            lab = {k: heads[k][int(pr[k][i].argmax())] for k in heads}
            conf = {f"{k}_conf": round(float(pr[k][i].max()), 3) for k in heads if k != "emotion"}
            span_preds.append({
                "voice": sp["voice"],
                "text": sp["text"],
                **lab,
                "confidence": round(float(pr["emotion"][i].max()), 3),
                **conf,
            })

        novel_lines = []
        by_ch: dict[int, list[str]] = {}
        annotated_by_ch: dict[int, list[str]] = {}

        for r, (s_start, s_end, _) in zip(rows, para_span_ranges):
            p_spans = span_preds[s_start:s_end]
            # Primary paragraph-level summary (prefer dialogue span if present, else first span) for backward compat
            dlg_spans = [s for s in p_spans if s["voice"] == "dialogue"]
            primary = dlg_spans[0] if dlg_spans else p_spans[0]
            ch_num = int(r["chapter"])
            p_idx = int(r["paragraph"])
            annotated_text = hf.annotate_paragraph(r["text"], p_spans)
            annotated_by_ch.setdefault(ch_num, []).append(annotated_text)

            ch_row = {
                "paragraph": p_idx,
                "emotion": primary["emotion"],
                "style": primary["style"],
                "sfx": primary["sfx"],
                "confidence": primary["confidence"],
                "style_conf": primary["style_conf"],
                "sfx_conf": primary["sfx_conf"],
                "spans": p_spans,
            }
            by_ch.setdefault(ch_num, []).append(json.dumps(ch_row, ensure_ascii=False) + "\n")
            novel_lines.append(json.dumps({"chapter": ch_num, **ch_row}, ensure_ascii=False) + "\n")

        # Save per-chapter tags (for Phase 2 if running on same box) and combined novel JSONL
        ch_tag_dir = work / "novels" / novel / "tags"
        ch_tag_dir.mkdir(parents=True, exist_ok=True)
        for ch, ch_lns in by_ch.items():
            (ch_tag_dir / f"{ch:05d}.jsonl").write_text("".join(ch_lns))

        # Write updated chapter_<N>.txt.gz files with inline <|voice:...|emotion:...|> tags
        novel_ch_out = out_ch_dir / novel
        novel_ch_out.mkdir(parents=True, exist_ok=True)
        novel_put_ch = put_ch_urls.get(novel) or {}
        for ch, paras_annotated in annotated_by_ch.items():
            ch_txt = "\n\n".join(paras_annotated)
            ch_gz = gzip.compress(ch_txt.encode("utf-8"), compresslevel=9)
            ch_rel = f"chapters/{novel}/chapter_{ch}.txt.gz"
            (novel_ch_out / f"chapter_{ch}.txt.gz").write_bytes(ch_gz)
            sums_lines.append(f"{hashlib.sha256(ch_gz).hexdigest()}  {ch_rel}\n")
            if str(ch) in novel_put_ch:
                http_put(novel_put_ch[str(ch)], ch_gz, "text/plain")

        fname = f"{novel}_{model_name}.jsonl"
        payload = "".join(novel_lines).encode("utf-8")
        (out_tags_dir / fname).write_bytes(payload)
        sums_lines.append(f"{hashlib.sha256(payload).hexdigest()}  {fname}\n")

        if novel in put_novel_urls:
            http_put(put_novel_urls[novel], payload, "application/x-ndjson")

        done_paras += len(rows)
        elapsed = time.perf_counter() - t_start
        log(f"  {novel:42} {len(rows):7,} paras ({len(span_inputs):7,} spans) in {dt:5.1f}s "
            f"({len(span_inputs) / max(dt, 1e-6):6.0f} spans/s) | total {done_paras:,}/{total_paras:,}")

    del model
    if torch.cuda.is_available():
        torch.cuda.empty_cache()
    elif torch.backends.mps.is_available():
        torch.mps.empty_cache()

    (out_tags_dir / "SHA256SUMS").write_text("".join(sums_lines))
    tar_buf = io.BytesIO()
    with tarfile.open(fileobj=tar_buf, mode="w:gz") as tar:
        for f in sorted(out_tags_dir.iterdir()):
            tar.add(f, arcname=f.name, recursive=True)
    tar_bytes = tar_buf.getvalue()
    (work / "tags_output.tar.gz").write_bytes(tar_bytes)

    if arch.get("put_archive_url"):
        http_put(arch["put_archive_url"], tar_bytes, "application/gzip")
        log(f"[phase 1 archive] uploaded tags_output.tar.gz ({len(tar_bytes) / 1e6:.2f} MB, {len(by_novel)} novels)")


def run_phase1_tagging(bundle: dict, work: Path, novels_filter: set[str] | None) -> None:
    """Phase 1: Tag every novel's paragraphs with DeBERTa-v3-large on GPU and upload tags JSONL to R2."""
    if bundle.get("archive"):
        return run_phase1_archive(bundle, work, novels_filter)
    ckpt = ensure_tagger_model(bundle, work)
    import torch
    import tag_novel

    device = torch.device("cuda" if torch.cuda.is_available() else ("mps" if torch.backends.mps.is_available() else "cpu"))
    bs = 256 if device.type == "cuda" else 32

    for njob in bundle["novels"]:
        novel = njob["novel"]
        if novels_filter and novel not in novels_filter:
            continue
        if not re.fullmatch(r"[a-z0-9-]+", novel):
            sys.exit(f"invalid novel id: {novel!r}")

        novel_dir = work / "novels" / novel
        tag_dir = novel_dir / "tags"
        tag_dir.mkdir(parents=True, exist_ok=True)
        combined_path = novel_dir / f"{novel}_{bundle['settings']['model']}.jsonl"

        texts, _ = download_novel_chapters(njob, novel_dir / "chapters")
        missing_chs = [ch for ch in sorted(texts) if not (tag_dir / f"{ch:05d}.jsonl").exists()]

        if not missing_chs and combined_path.exists():
            log(f"[phase 1] {novel}: all {len(texts)} chapters already tagged locally")
            continue

        # If tags already exist in R2 and we have a presigned GET URL, pull and split by chapter
        if njob.get("tags_already_in_r2") and njob.get("get_tags_url") and missing_chs:
            try:
                log(f"[phase 1] {novel}: fetching existing tags from R2 ...")
                raw_lines = http_get(njob["get_tags_url"]).decode("utf-8").splitlines()
                by_ch: dict[int, list[dict]] = {}
                for ln in raw_lines:
                    if not ln.strip():
                        continue
                    row = json.loads(ln)
                    by_ch.setdefault(int(row["chapter"]), []).append(row)
                for ch, ps in texts.items():
                    if ch in by_ch and len(by_ch[ch]) == len(ps):
                        (tag_dir / f"{ch:05d}.jsonl").write_text(
                            "".join(json.dumps(r) + "\n" for r in by_ch[ch])
                        )
                missing_chs = [ch for ch in sorted(texts) if not (tag_dir / f"{ch:05d}.jsonl").exists()]
            except Exception as e:
                log(f"[phase 1] {novel}: R2 tag fetch skipped ({e}); tagging on GPU")

        if missing_chs:
            rows = [
                {"chapter": ch, "paragraph": i, "text": t, "prev": texts[ch][i - 1] if i else ""}
                for ch in missing_chs for i, t in enumerate(texts[ch])
            ]
            log(f"[phase 1] {novel}: tagging {len(rows)} paragraphs across {len(missing_chs)} chapters on {device.type} ...")
            tags = tag_novel.tag_rows(rows, [str(ckpt)], device, log=log, bs=bs)
            by_ch_new: dict[int, list[dict]] = {ch: [] for ch in missing_chs}
            for r, t in zip(rows, tags):
                by_ch_new[r["chapter"]].append({"paragraph": r["paragraph"], **t})
            for ch, ts in by_ch_new.items():
                (tag_dir / f"{ch:05d}.jsonl").write_text("".join(json.dumps(x) + "\n" for x in ts))

        # Write full novel tags file and upload to R2 if presigned PUT is present
        all_lines = []
        for ch in sorted(texts):
            ch_lines = (tag_dir / f"{ch:05d}.jsonl").read_text().splitlines()
            for ln in ch_lines:
                if ln.strip():
                    d = json.loads(ln)
                    all_lines.append(json.dumps({"chapter": ch, **d}) + "\n")
        combined_bytes = "".join(all_lines).encode("utf-8")
        combined_path.write_bytes(combined_bytes)

        if njob.get("put_tags_url") and not njob.get("tags_already_in_r2"):
            http_put(njob["put_tags_url"], combined_bytes, "application/x-ndjson")
            log(f"[phase 1] {novel}: uploaded {len(all_lines)} paragraph tags to R2 ({len(combined_bytes) / 1e6:.1f} MB)")

    if torch.cuda.is_available():
        torch.cuda.empty_cache()
    log("[phase 1] emotion tagging complete")


def loudnorm_filter(wav: Path) -> str:
    """Measure integrated loudness on full chapter WAV and return uniform chapter gain + peak limiter."""
    r = subprocess.run(
        ["ffmpeg", "-hide_banner", "-nostats", "-i", str(wav), "-af", "loudnorm=print_format=json", "-f", "null", "-"],
        capture_output=True, text=True, check=True,
    )
    i = r.stderr.rindex("{")
    measured = float(json.loads(r.stderr[i:r.stderr.index("}", i) + 1])["input_i"])
    return f"volume={TARGET_LUFS - measured:.2f}dB,alimiter=limit={LIMIT}:level=false"


FORMATS = {  # bundle settings["format"] -> file extension, ffmpeg codec args, Content-Type
    "mp3": (".mp3", ["-codec:a", "libmp3lame"], "audio/mpeg"),
    "opus": (".opus", ["-codec:a", "libopus", "-vbr", "on", "-application", "audio"], "audio/ogg"),
}


def to_mp3(wav: Path, mp3: Path, af: str, bitrate: str, fmt: str = "mp3") -> None:
    mp3.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        ["ffmpeg", "-loglevel", "error", "-y", "-i", str(wav), "-af", af, "-ac", "1", "-ar", "24000",
         *FORMATS[fmt][1], "-b:a", bitrate, str(mp3)],
        check=True,
    )


def upload_chapter_bundle(ch_spec: dict, novel_dir: Path, voices_meta: dict, variant: str = "dual",
                          content_type: str = "audio/mpeg") -> None:
    """Upload title + 0..N-1 audio files + manifest.json to R2 using presigned PUT URLs."""
    ch = int(ch_spec["chapter"])
    man_path = novel_dir / "manifest" / variant / f"{ch:05d}.json"
    man = json.loads(man_path.read_text())
    mp3_dir = novel_dir / "mp3" / variant / f"{ch:05d}"
    put_urls: dict[str, str] = ch_spec["put_mp3_urls"]

    entries = [man["title"], *man["paragraphs"]]
    for entry in entries:
        fname = entry["file"]
        fpath = mp3_dir / fname
        if not fpath.exists():
            raise RuntimeError(f"missing encoded file {fpath}")
        if fname not in put_urls:
            raise RuntimeError(f"paragraph count mismatch: {fname} not in presigned PUT map")
        raw = fpath.read_bytes()
        entry.update(bytes=len(raw), sha256=hashlib.sha256(raw).hexdigest())

    def put_one(entry: dict) -> int:
        fname = entry["file"]
        raw = (mp3_dir / fname).read_bytes()
        http_put(put_urls[fname], raw, content_type)
        return len(raw)

    with ThreadPoolExecutor(6) as pool:
        total_bytes = sum(pool.map(put_one, entries))

    man.update(voices=voices_meta, prefix=ch_spec["r2_prefix"])
    man_bytes = json.dumps(man, indent=1, ensure_ascii=False).encode("utf-8")
    http_put(ch_spec["put_manifest_url"], man_bytes, "application/json")
    (novel_dir / "manifest" / variant / f"{ch:05d}.uploaded.json").write_bytes(man_bytes)
    log(f"  uploaded {ch_spec['r2_prefix']}: {len(entries)} audio files + manifest ({total_bytes / 1e6:.2f} MB)")


def cleanup_chapter_files(novel_dir: Path, ch: int, variant: str = "dual") -> None:
    """Remove bulky WAV/MP3 files for a chapter once uploaded so 1000s of chapters fit on disk."""
    for p in (
        novel_dir / "wav" / variant / f"{ch:05d}.wav",
        novel_dir / "mp3" / variant / f"{ch:05d}.mp3",
    ):
        p.unlink(missing_ok=True)
    for d in (
        novel_dir / "paras" / variant / f"{ch:05d}",
        novel_dir / "mp3" / variant / f"{ch:05d}",
    ):
        shutil.rmtree(d, ignore_errors=True)
    shutil.rmtree(novel_dir / "cache", ignore_errors=True)


def locked_clip_checker():
    """One Whisper model shared by the render threads; the transformers pipeline is not thread-safe."""
    import threading

    import check_audio

    _, transcribe = check_audio.transcribe_setup()
    lock = threading.Lock()

    def locked(clip, sr):
        with lock:
            return transcribe(clip, sr)

    return render_mod.clip_checker(locked)


def run_phase2_audio(bundle: dict, work: Path, url: str, backend_name: str, higgs_variant: str,
                     skip_whisper: bool, keep_files: bool, novels_filter: set[str] | None,
                     ramp=None, on_chapter=None) -> dict:
    """Phase 2: Synthesize Whisper-checked dual-voice audio per chapter, encode it, and upload to R2.

    Returns {"uploaded": [...], "held": [...]} as "<novel>/<chapter>" strings.
    """
    narrator_wav, dialogue_wav, ref_text_path = ensure_voices(bundle, work)
    settings = bundle["settings"]
    voices_meta = {"narrator": settings["narrator"], "dialogue": settings["dialogue"]}
    bitrate = settings.get("bitrate", "64k")
    temp = float(settings.get("temperature", 0.8))
    fmt = settings.get("format", "mp3")
    ext, _, content_type = FORMATS[fmt]
    workers = int(settings.get("workers", 1))

    import synth
    ref_text = ref_text_path.read_text().strip()
    voices_arg = {"narrator": (str(narrator_wav), ref_text), "dialogue": (str(dialogue_wav), ref_text)}
    tts = synth.backend(backend_name, variant=higgs_variant, url=url, voices=voices_arg, sampling={"temperature": temp})

    check = None if skip_whisper else locked_clip_checker()

    cuts = hf.Cuts()
    summary: dict[str, list[str]] = {"uploaded": [], "held": []}

    for njob in bundle["novels"]:
        novel = njob["novel"]
        if novels_filter and novel not in novels_filter:
            continue
        chapters_specs = [c for c in njob["chapters"] if "put_mp3_urls" in c]
        if not chapters_specs:
            continue

        novel_dir = work / "novels" / novel
        texts, _ = download_novel_chapters(njob, novel_dir / "chapters")

        for ch_spec in chapters_specs:
            ch = int(ch_spec["chapter"])
            uploaded_marker = novel_dir / "manifest" / "dual" / f"{ch:05d}.uploaded.json"
            if uploaded_marker.exists():
                log(f"[phase 2] {novel} ch{ch}: already uploaded, skipping")
                continue

            ps = texts[ch]
            tag_file = novel_dir / "tags" / f"{ch:05d}.jsonl"
            if not tag_file.exists():
                sys.exit(f"missing tags for {novel} ch{ch}; run phase 1 first")
            ts = [json.loads(ln) for ln in tag_file.read_text().splitlines() if ln.strip()]
            title_line = f"Chapter {ch}: {ch_spec.get('title') or f'Chapter {ch}'}"
            reqs = render_mod.plan(ps, ts, "dual", cuts)

            t0 = time.perf_counter()
            width = ramp.workers if ramp else workers
            qa_status = "pending-whisper" if ramp is not None else None
            stats = render_mod.render(tts, novel, ch, "dual", title_line, ps, reqs, ts, novel_dir, log, check,
                                      width, ext, ramp=ramp, qa_status=qa_status)
            wall_s = time.perf_counter() - t0
            log(f"[phase 2] {novel} ch{ch}: rendered {stats['audio_s'] / 60:.1f}m audio in {wall_s:.1f}s "
                f"({stats['audio_s'] / max(wall_s, 1e-9):.1f}x realtime, bursts dropped {stats['bursts_dropped']}, "
                f"check retries {stats['check_retries']})")

            if stats["check_failed"]:
                # A clip still skipped or garbled words after every retry: keep the chapter off R2 for review.
                report = {"novel": novel, "chapter": ch, "failed": stats["check_failed"]}
                held = novel_dir / "held" / f"{ch:05d}.json"
                held.parent.mkdir(parents=True, exist_ok=True)
                held.write_text(json.dumps(report, indent=1, ensure_ascii=False))
                if ch_spec.get("put_held_url"):
                    http_put(ch_spec["put_held_url"], json.dumps(report, indent=1, ensure_ascii=False).encode(),
                             "application/json")
                log(f"[phase 2] {novel} ch{ch}: HELD, {len(stats['check_failed'])} clip(s) failed the Whisper "
                    f"check after {render_mod.CHECK_ATTEMPTS} attempts -> {held}")
                summary["held"].append(f"{novel}/{ch}")
                if on_chapter:
                    on_chapter(summary)
                if not keep_files:
                    cleanup_chapter_files(novel_dir, ch, "dual")
                continue

            ch_wav = novel_dir / "wav" / "dual" / f"{ch:05d}.wav"
            af = loudnorm_filter(ch_wav)
            para_wavs = sorted((novel_dir / "paras" / "dual" / f"{ch:05d}").glob("*.wav"))
            with ThreadPoolExecutor(8) as pool:
                list(pool.map(lambda w: to_mp3(w, novel_dir / "mp3" / "dual" / f"{ch:05d}" / f"{w.stem}{ext}",
                                               af, bitrate, fmt), para_wavs))

            upload_chapter_bundle(ch_spec, novel_dir, voices_meta, "dual", content_type)
            summary["uploaded"].append(f"{novel}/{ch}")
            if on_chapter:
                on_chapter(summary)
            if not keep_files:
                cleanup_chapter_files(novel_dir, ch, "dual")

    log("[phase 2] library audio rendering & upload complete")
    return summary


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--bundle", type=Path, required=True, help="presigned job_bundle.json")
    p.add_argument("--work", type=Path, default=Path("/workspace/audiobook_job"), help="local scratch directory on GPU")
    p.add_argument("--phase", choices=["both", "tags", "audio"], default="both")
    p.add_argument("--novels", nargs="*", help="optional subset of novel slugs from the bundle")
    p.add_argument("--backend", choices=["sglang", "mlx"], default="sglang")
    p.add_argument("--higgs", choices=["4bit", "8bit", "bf16"], default="4bit")
    p.add_argument("--url", default="http://127.0.0.1:8000", help="local SGLang-Omni endpoint")
    p.add_argument("--skip-whisper", action="store_true",
                   help="skip the per-clip Whisper check (no retries; garbled clips get uploaded) - tests only")
    p.add_argument("--keep-files", action="store_true", help="keep local WAV/MP3 files after R2 upload")
    a = p.parse_args()

    bundle = json.loads(a.bundle.read_text())
    a.work.mkdir(parents=True, exist_ok=True)
    novels_filter = set(a.novels) if a.novels else None

    if a.phase in ("both", "tags"):
        run_phase1_tagging(bundle, a.work, novels_filter)
    if a.phase in ("both", "audio"):
        run_phase2_audio(bundle, a.work, a.url, a.backend, a.higgs, a.skip_whisper, a.keep_files, novels_filter)


if __name__ == "__main__":
    main()
