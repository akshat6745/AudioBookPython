#!/usr/bin/env python3
"""Standalone, unattended GPU worker: Phase 1 (emotion tagging) -> Phase 2 (Higgs v3 audio rendering & upload).

Runs on any Linux CUDA GPU (Beam.cloud, Vast.ai, RunPod, etc.) with ZERO cloud credentials and ZERO connection
back to the user's Mac. Everything is driven by the presigned job_bundle.json generated by presign_library.py.

Workflow:
  1. Download & SHA-256-verify the trained emotion tagger (`deberta3large_teacher2`) from R2 via presigned GET.
  2. Unpack & SHA-256-verify the fixed reference voices (`default_seed8`, `default_seed2`) embedded in the bundle.
  3. Phase 1 (Emotion Tagging):
       For every novel in the bundle, fetch all chapter texts via presigned GET, split into paragraphs using
       the exact backend contract (`text.split("\\n\\n")`), run `tag_novel.tag_rows` on CUDA (fp16/bf16),
       save `<work>/tags/<novel>/<ch>.jsonl`, and upload `<novel>_<model>.jsonl` to R2 via presigned PUT.
       Frees the tagger from GPU VRAM before Phase 2.
  4. Phase 2 (Audio Synthesis + PostFX + Whisper Check + Loudnorm + Upload):
       Ensure SGLang-Omni Higgs v3 server is running on 127.0.0.1:8000.
       For each novel & chapter:
         - Render dual-voice WAVs (`render.py --backend sglang --skip-tag`) with `postfx.tidy` end-burst removal
         - Whisper-check every clip as it is made (`verify.py`); regenerate rejects with new seeds, and hold the
           chapter back (work/novels/<novel>/held/<ch>.json, no upload) if a clip never passes
         - Chapter-wide loudness normalization (-18 LUFS + peak limiter) -> 64k mono 24kHz MP3s (`title.mp3`, `0..N-1.mp3`)
         - Upload all MP3s + `manifest.json` (with `text_sha256`, `bytes`, `sha256`, `duration_s`) via presigned PUTs
         - Delete local chapter intermediates so disk usage stays bounded across the entire library.

Usage:
  python3 scripts/gpu_tts/audiobook/gpu_library_worker.py --bundle job_bundle.json [--work /workspace/audiobook_job]
  python3 scripts/gpu_tts/audiobook/gpu_library_worker.py --bundle job_bundle.json --phase tags
  python3 scripts/gpu_tts/audiobook/gpu_library_worker.py --bundle job_bundle.json --phase audio
"""
